#!/usr/bin/env node
// Collects every mirror file's header into docs/parity-status.md (ARCHITECTURE.md §12.1):
//   Rust  //! mirror: reference/<path>.js[, reference/<path2>.js]    JS  // mirror: …
//         //! parity: MISSING | FAITHFUL | DIVERGENT(<ID>)               // parity: …
// A mirror file's fixture count = fixture files under crates/*/tests/fixtures/** naming its vanilla file as
// "<parent dir>/<file>.js" (the scenario tag form, e.g. "creeps/harvest.js:12").
// Exits 1 when a mirror file has no parity line, a FAITHFUL file has no fixtures, or (when the reference
// sources exist: ./reference or $CHITIN_REFERENCE) a mirror path does not exist.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const refRoot = process.env.CHITIN_REFERENCE || path.join(root, 'reference');
const rel = p => path.relative(root, p).split(path.sep).join('/');

function walk(dir, keep, out = []) {
    if (!fs.existsSync(dir)) return out;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) {
            if (!['target', 'vendor', 'node_modules', '.git'].includes(e.name)) walk(p, keep, out);
        } else if (keep(p)) out.push(p);
    }
    return out;
}

// Fixture tags: every "<dir>/<file>.js" token, counted once per fixture file.
const fixtureCount = new Map();
for (const crate of fs.readdirSync(path.join(root, 'crates'))) {
    for (const f of walk(path.join(root, 'crates', crate, 'tests', 'fixtures'), () => true)) {
        const tags = new Set(fs.readFileSync(f, 'latin1').match(/[\w.-]+\/[\w.-]+\.js/g) || []);
        for (const t of tags) fixtureCount.set(t, (fixtureCount.get(t) || 0) + 1);
    }
}

const rows = [];
const errors = [];
const sources = walk(path.join(root, 'crates'), p => /\.(rs|js)$/.test(p) && !p.includes(`${path.sep}fixtures${path.sep}`));
for (const file of sources.sort()) {
    const head = fs.readFileSync(file, 'utf8').split('\n', 6);
    const field = name => {
        const line = head.find(l => new RegExp(`^//!? ${name}: `).test(l));
        return line && line.replace(new RegExp(`^//!? ${name}: `), '').trim();
    };
    const mirror = field('mirror');
    if (!mirror) continue;
    // The status token may be followed by an explanation ("DIVERGENT(X): why", "FAITHFUL (fixtures: …)").
    const raw = field('parity');
    const parity = raw && ((raw.match(/^(MISSING|FAITHFUL|DIVERGENT\([\w-]+(, *[\w-]+)*\))(?=$|[\s:(])/) || [])[1] || raw);
    const paths = mirror.split(',').map(s => s.trim());
    const fixtures = paths.reduce((n, p) => n + (fixtureCount.get(p.split('/').slice(-2).join('/')) || 0), 0);
    if (!parity) errors.push(`${rel(file)}: mirror header without a parity line`);
    else if (parity === 'FAITHFUL' && fixtures === 0) errors.push(`${rel(file)}: FAITHFUL without fixtures`);
    else if (!/^(MISSING|FAITHFUL|DIVERGENT\([\w-]+(, *[\w-]+)*\))$/.test(parity)) errors.push(`${rel(file)}: bad parity "${parity}"`);
    if (fs.existsSync(refRoot)) {
        for (const p of paths) {
            if (!p.startsWith('reference/') || !fs.existsSync(path.join(refRoot, p.slice('reference/'.length)))) {
                errors.push(`${rel(file)}: mirror path ${p} not found`);
            }
        }
    }
    rows.push({ file: rel(file), mirror: paths.map(p => p.replace(/^reference\//, '')).join(', '), parity: parity || '?', fixtures });
}

const status = r => r.parity.replace(/\(.*$/, '');
const totals = {};
for (const r of rows) totals[status(r)] = (totals[status(r)] || 0) + 1;
const md = [
    '# Parity status',
    '',
    'Generated by `node tools/parity-report.js` from the mirror headers; do not edit.',
    '',
    '| parity | files |',
    '|---|---|',
    ...Object.keys(totals).sort().map(k => `| ${k} | ${totals[k]} |`),
    `| total | ${rows.length} |`,
    '',
    '| file | mirror of (reference/) | parity | fixtures |',
    '|---|---|---|---|',
    ...rows.map(r => `| ${r.file} | ${r.mirror} | ${r.parity} | ${r.fixtures} |`),
    '',
].join('\n');
fs.writeFileSync(path.join(root, 'docs', 'parity-status.md'), md);

console.log(`${rows.length} mirror files: ${Object.keys(totals).sort().map(k => `${k} ${totals[k]}`).join(', ')}`);
for (const e of errors) console.error(e);
process.exit(errors.length ? 1 : 0);
